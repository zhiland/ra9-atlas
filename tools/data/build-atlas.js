'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { validateAtlas } = require('../../prototype/validate-atlas-data');
const object = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const id = value => typeof value === 'string' && value.length > 0;
function requireShape(value, keys, name) {
  if (!object(value) || Object.keys(value).sort().join(',') !== [...keys].sort().join(',')) {
    throw new Error(`${name}: expected fields ${keys.join(', ')}`);
  }
}
function compileSource(source, ledger) {
  requireShape(source, ['format', 'version', 'atlas'], 'source');
  requireShape(ledger, ['format', 'version', 'nodes', 'edges'], 'ledger');
  if (source.format !== 'ra9-atlas.atlas-source' || source.version !== 1) throw new Error('Unsupported source format/version');
  if (ledger.format !== 'ra9-atlas.legacy-index' || ledger.version !== 1) throw new Error('Unsupported ledger format/version');
  if (!object(source.atlas) || !Array.isArray(source.atlas.nodes) || !Array.isArray(source.atlas.edges)) throw new Error('Atlas requires node and edge arrays');
  if (!Array.isArray(ledger.nodes) || !Array.isArray(ledger.edges)) throw new Error('Ledger requires node and edge arrays');
  const atlas = source.atlas;
  if (atlas.nodes.length !== ledger.nodes.length || atlas.edges.length !== ledger.edges.length) throw new Error('Ledger length differs from atlas');
  ledger.nodes.forEach((nodeId, i) => {
    if (!id(nodeId) || !object(atlas.nodes[i]) || atlas.nodes[i].id !== nodeId) throw new Error(`Node ledger mismatch at ${i}`);
  });
  ledger.edges.forEach((record, i) => {
    requireShape(record, ['id', 'from', 'to', 'fromOption'], `ledger.edges[${i}]`);
    if (![record.id, record.from, record.to].every(id) || !(record.fromOption === null || (Number.isInteger(record.fromOption) && record.fromOption >= 0))) throw new Error(`Invalid edge ledger record at ${i}`);
    const edge = atlas.edges[i];
    if (!object(edge) || ['id', 'from', 'to'].some(key => edge[key] !== record[key]) || (edge.fromOption ?? null) !== record.fromOption) throw new Error(`Edge ledger mismatch at ${i}`);
  });
  function rejectUnsafeKeys(value) {
    if (value === null || typeof value !== 'object') return;
    for (const key of Object.keys(value)) {
      if (key === '__proto__') throw new Error('Unsupported object-literal key: __proto__');
      rejectUnsafeKeys(value[key]);
    }
  }
  rejectUnsafeKeys(atlas);
  const result = validateAtlas(atlas);
  if (result.failed) throw new Error(result.checks.filter(check => check.errors.length).map(check => `${check.name}: ${check.errors.join('; ')}`).join('\n'));
  return '// Generated by tools/data/build-atlas.js. Edit data/atlas.source.json.\nconst ATLAS = ' + JSON.stringify(atlas, null, 2) + ';\n';
}

function main(args) {
  const root = path.resolve(__dirname, '../..');
  const options = { source: path.join(root, 'data/atlas.source.json'), ledger: path.join(root, 'data/legacy-index.json'), out: path.join(root, 'prototype/atlas-data.js'), check: false };
  for (let i = 0; i < args.length; i++) {
    const flag = args[i];
    if (flag === '--check') { options.check = true; continue; }
    if (!['--source', '--ledger', '--out'].includes(flag)) throw new Error(`Unknown flag: ${flag}`);
    if (!args[i + 1] || args[i + 1].startsWith('--')) throw new Error(`Missing value for ${flag}`);
    options[flag.slice(2)] = path.resolve(args[++i]);
  }
  const output = compileSource(JSON.parse(fs.readFileSync(options.source, 'utf8')), JSON.parse(fs.readFileSync(options.ledger, 'utf8')));
  if (options.check) {
    if (!fs.existsSync(options.out) || !fs.readFileSync(options.out).equals(Buffer.from(output))) throw new Error('Generated atlas missing or stale; run npm run build:data');
    console.log('Generated atlas is current');
  } else {
    const staging = fs.mkdtempSync(`${options.out}.`);
    const temporary = path.join(staging, 'atlas.js');
    try { fs.writeFileSync(temporary, output, { flag: 'wx' }); fs.renameSync(temporary, options.out); }
    finally { fs.rmSync(staging, { recursive: true, force: true }); }
    console.log('Generated atlas written');
  }
}
module.exports = { compileSource };
if (require.main === module) {
  try { main(process.argv.slice(2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
